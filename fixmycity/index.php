<?php
declare(strict_types=1);

// 1. Secure session configuration (ini_set BEFORE session_start)
ini_set('session.use_strict_mode', '1');   // reject session IDs not generated by the server
ini_set('session.cookie_httponly', '1');   // cookie invisible to JavaScript (XSS)
ini_set('session.cookie_samesite', 'Lax'); // limits CSRF through third-party cookies
// ini_set('session.cookie_secure', '1');  // uncomment when the site is served in HTTPS
session_start();

// 2. Session expiration after 30 minutes of inactivity
$sessionLifetime = 1800;
if (isset($_SESSION['last_activity']) && (time() - $_SESSION['last_activity'] > $sessionLifetime)) {
    $_SESSION = [];
    session_destroy();
    session_start();
}
$_SESSION['last_activity'] = time();

// 3. HTTP security headers
header('X-Frame-Options: DENY');
header('X-Content-Type-Options: nosniff');
header('Referrer-Policy: strict-origin-when-cross-origin');
// 'self' for scripts (so no inline <script> / onclick in the views); blob: = photo preview before upload
header("Content-Security-Policy: default-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:");

// 4. Controllers
require_once __DIR__ . '/controllers/AuthController.php';   // teammate's file (stub until the merge)
require_once __DIR__ . '/controllers/ReportController.php';

$authController   = new AuthController();
$reportController = new ReportController($authController);

// 5. Routing
$action = $_GET['action'] ?? 'report_form';

switch ($action) {
    case 'csrf':
        header('Content-Type: application/json; charset=utf-8');
        echo json_encode(['token' => $authController->getCsrfToken()]);
        break;
    case 'register':
        $authController->register();
        break;
    case 'login':
        $authController->login();
        break;
    case 'forgot_password':
        $authController->forgotPassword();
        break;
    case 'reset_password':
        $authController->resetPassword();
        break;
    case 'logout':
        $authController->logout();
        break;

    // ---------------- FRONT OFFICE (any authenticated user) ----------------
    case 'report_form':
        $reportController->showReportForm();
        break;
    case 'report_create':          // POST
        $reportController->createReport();
        break;
    case 'reports':                // "All reports" or ?mine=1 "My reports"
        $reportController->showReports();
        break;
    case 'report_edit':
        $reportController->showEditReport();
        break;
    case 'report_update':          // POST
        $reportController->updateReport();
        break;
    case 'report_delete':          // POST
        $reportController->deleteReport();
        break;
    case 'info':
        $reportController->showInfo();
        break;

    // ---------------- BACK OFFICE (role: admin only) ----------------
    case 'admin_reports':
        $reportController->showAdminReports();
        break;
    case 'admin_report_status':    // POST
        $reportController->changeReportStatus();
        break;
    case 'admin_report_delete':    // POST
        $reportController->deleteAdminReport();
        break;
    case 'admin_categories':
        $reportController->showAdminCategories();
        break;
    case 'admin_category_save':    // POST
        $reportController->saveCategory();
        break;
    case 'admin_category_delete':  // POST
        $reportController->deleteCategory();
        break;

    default:
        http_response_code(404);
        echo '404 - Page not found';
        break;
}
